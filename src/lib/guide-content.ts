export interface GuideShot {
  /** 파일 이름(확장자 없음). 이미지 경로는 `guideShotSrc`가 만들어요. */
  id: string;
  alt: string;
  caption: string;
}

export interface GuideStep {
  title: string;
  description: string;
  /** 이 단계를 보여주는 화면(`shots`의 id). */
  shot?: string;
}

export interface GuideButton {
  name: string;
  description: string;
}

export interface GuideProblem {
  problem: string;
  cause: string;
  fix: string;
}

export const GUIDE_SLUGS = ["diagnosis", "calendar", "blog", "shorts", "growth-report", "home", "channels", "billing"] as const;
export type GuideSlug = (typeof GUIDE_SLUGS)[number];

export interface Guide {
  slug: GuideSlug;
  title: string;
  summary: string;
  icon: LucideIcon;
  /** 무료 기능이면 true, 이용권이 필요하면 false */
  free: boolean;
  /** 이 기능이 무엇을 위한 것인지 */
  what: string;
  whoFor: string[];
  prepare: string[];
  /** 어디서 들어가는지 */
  enter: { menu: string; href: string; how: string };
  steps: GuideStep[];
  inputs: string[];
  examples: string[];
  buttons: GuideButton[];
  results: string[];
  problems: GuideProblem[];
  tips: string[];
  /** 같이 보면 좋은 이용방법 */
  related: GuideSlug[];
  cta: { href: string; label: string };
  shots: GuideShot[];
}

/** 화면 이미지 경로 규칙: `/guide/<기능>/<id>.png`(PC), `/guide/<기능>/<id>-m.png`(휴대폰). */
export function guideShotSrc(slug: GuideSlug, id: string, device: "desktop" | "mobile" = "desktop"): string {
  return `/guide/${slug}/${id}${device === "mobile" ? "-m" : ""}.png`;
}

