import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";

function parseEnvFile(contents) {
  const values = {};
  for (const line of contents.split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

async function upsertAuthUser(admin, account) {
  const { data: listed, error: listError } = await admin.auth.admin.listUsers({ page: 1, perPage: 100 });
  if (listError) throw listError;
  const existing = listed.users.find((user) => user.email?.toLowerCase() === account.email.toLowerCase());
  const attributes = {
    password: account.password,
    email_confirm: true,
    user_metadata: { display_name: account.displayName },
    app_metadata: { role: account.role, local_seed: true },
  };
  const result = existing
    ? await admin.auth.admin.updateUserById(existing.id, attributes)
    : await admin.auth.admin.createUser({ email: account.email, ...attributes });
  if (result.error || !result.data.user) throw result.error ?? new Error(`${account.email} 계정을 만들지 못했습니다.`);

  const { error: profileError } = await admin.from("profiles").upsert({
    id: result.data.user.id,
    email: account.email,
    display_name: account.displayName,
  });
  if (profileError) throw profileError;
  return result.data.user;
}

async function verifyPasswordLogin(url, publicKey, account) {
  const client = createClient(url, publicKey, { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } });
  const { data, error } = await client.auth.signInWithPassword({ email: account.email, password: account.password });
  if (error || !data.user) throw error ?? new Error(`${account.email} 로그인 검증에 실패했습니다.`);
  await client.auth.signOut();
}

async function main() {
  const statusFile = process.argv[2];
  const repoRoot = process.argv[3];
  if (!statusFile || !repoRoot) throw new Error("Usage: node scripts/seed-dev-users.mjs <status-env-file> <repo-root>");
  const status = parseEnvFile(await readFile(statusFile, "utf8"));
  const url = status.API_URL ?? status.SUPABASE_URL;
  const publicKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
  const serviceKey = status.SERVICE_ROLE_KEY ?? status.SECRET_KEY;
  if (!url || !publicKey || !serviceKey) throw new Error("supabase status 출력에서 API URL 또는 로컬 키를 찾지 못했습니다.");

  const accounts = [
    {
      role: "admin",
      email: process.env.DEV_ADMIN_EMAIL ?? "admin@autobiz.local",
      password: process.env.DEV_ADMIN_PASSWORD ?? "Admin1234!",
      displayName: "로컬 관리자",
    },
    {
      role: "user",
      email: process.env.DEV_USER_EMAIL ?? "user@autobiz.local",
      password: process.env.DEV_USER_PASSWORD ?? "User1234!",
      displayName: "로컬 사용자",
    },
  ];

  const admin = createClient(url, serviceKey, { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } });
  for (const account of accounts) {
    await upsertAuthUser(admin, account);
    await verifyPasswordLogin(url, publicKey, account);
    console.log(`[dev-db] ${account.role} 로그인 검증 완료: ${account.email}`);
  }

  const envPath = path.join(path.resolve(repoRoot), ".env.local.supabase");
  await writeFile(envPath, [
    "# Generated by scripts/dev-db.sh. Local development only.",
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${publicKey}`,
    `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
    "NEXT_PUBLIC_SITE_URL=http://localhost:3000",
    "AI_PROVIDER=mock",
    "BILLING_PROVIDER=mock",
    "",
  ].join("\n"), { mode: 0o600 });
  console.log(`[dev-db] Next.js 환경 파일 생성: ${envPath}`);
}

main().catch((error) => {
  console.error(`[dev-db] ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});

